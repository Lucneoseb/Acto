-- Verification : nombre de formats dans la categorie « Categorie », par langue.
select c.locale, c.label, count(i.id) as formats
  from public.idea_categories c
  left join public.idea_items i on i.category_id = c.id
 where c.slug = 'categorie'
 group by c.locale, c.label
 order by c.locale;
